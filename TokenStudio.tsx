import { useMemo, useState } from 'react'
import { Check, Copy, ExternalLink, ShieldCheck, Wallet } from 'lucide-react'

type EthereumProvider = { request(args: { method: string; params?: unknown[] }): Promise<unknown> }
declare global { interface Window { ethereum?: EthereumProvider } }

const BASE_SEPOLIA = '0x14a34'
const BASE_SEPOLIA_PARAMS = {
  chainId: BASE_SEPOLIA, chainName: 'Base Sepolia',
  nativeCurrency: { name: 'Ether', symbol: 'ETH', decimals: 18 },
  rpcUrls: ['https://sepolia.base.org'],
  blockExplorerUrls: ['https://sepolia.basescan.org'],
}
function solidityString(value: string) {
  return value.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/[\r\n]/g, ' ')
}

export default function TokenStudio({ lang }: { lang: 'ar' | 'fr' | 'en' }) {
  const isAr = lang === 'ar'
  const [name, setName] = useState('Example Token')
  const [symbol, setSymbol] = useState('EXM')
  const [supply, setSupply] = useState('1000000')
  const [wallet, setWallet] = useState('')
  const [chainId, setChainId] = useState('')
  const [message, setMessage] = useState('')
  const [copied, setCopied] = useState(false)
  const [busy, setBusy] = useState(false)
  const validSupply = (() => {
    if (!/^(0|[1-9][0-9]*)(\.[0-9]{1,18})?$/.test(supply)) return false
    try {
      const [whole, fraction = ''] = supply.split('.')
      const units = BigInt(whole) * 10n ** 18n + BigInt(fraction.padEnd(18, '0') || '0')
      return units > 0n && units <= (1n << 256n) - 1n
    } catch { return false }
  })()
  const valid = name.trim().length > 0 && name.length <= 64 && /^[A-Z0-9]{2,12}$/.test(symbol.trim().toUpperCase()) && validSupply
  const source = useMemo(() => {
    if (!validSupply) return '// Enter a valid token supply to generate this contract.'
    const parts = supply.split('.')
    const whole = parts[0] || '0'
    const fraction = (parts[1] || '').padEnd(18, '0')
    const units = (BigInt(whole) * 10n ** 18n + BigInt(fraction || '0')).toString()
    return [
      '// SPDX-License-Identifier: MIT',
      'pragma solidity ^0.8.24;',
      '',
      'import {ERC20} from "@openzeppelin/contracts/token/ERC20/ERC20.sol";',
      '',
      '/**',
      ' * Fixed-supply ERC-20 generated by AI Crypto Rain Token Studio.',
      ' * No owner, admin, upgrade, blacklist, tax, or post-deployment mint function.',
      ' */',
      'contract GeneratedToken is ERC20 {',
      '    constructor(address initialHolder)',
      '        ERC20("' + solidityString(name.trim()) + '", "' + solidityString(symbol.trim().toUpperCase()) + '")',
      '    {',
      '        require(initialHolder != address(0), "Invalid holder");',
      '        _mint(initialHolder, ' + units + ');',
      '    }',
      '}',
      ''
    ].join('\n')
  }, [name, symbol, supply, validSupply])

  async function connectWallet() {
    if (!window.ethereum) { setMessage(isAr ? 'لم يتم العثور على محفظة متوافقة مع Ethereum.' : 'No injected Ethereum wallet was found.'); return }
    setBusy(true); setMessage('')
    try {
      const accounts = await window.ethereum.request({ method: 'eth_requestAccounts' }) as string[]
      const currentChain = await window.ethereum.request({ method: 'eth_chainId' }) as string
      setWallet(accounts?.[0] || '')
      setChainId(currentChain || '')
      if (currentChain?.toLowerCase() !== BASE_SEPOLIA) {
        try {
          await window.ethereum.request({ method: 'wallet_switchEthereumChain', params: [{ chainId: BASE_SEPOLIA }] })
        } catch (switchError) {
          if ((switchError as { code?: number })?.code === 4902) {
            await window.ethereum.request({ method: 'wallet_addEthereumChain', params: [BASE_SEPOLIA_PARAMS] })
          } else throw switchError
        }
        const updated = await window.ethereum.request({ method: 'eth_chainId' }) as string
        setChainId(updated || '')
      }
      setMessage(isAr ? 'تم ربط المحفظة. لا يتم إرسال أي معاملة في هذه المرحلة.' : 'Wallet connected. No transaction is sent in this preview phase.')
    } catch {
      setMessage(isAr ? 'تعذر ربط المحفظة أو تبديل الشبكة.' : 'Wallet connection or network switch was rejected.')
    } finally { setBusy(false) }
  }
  async function copySource() {
    try {
      await navigator.clipboard.writeText(source)
      setCopied(true); setMessage(isAr ? 'تم نسخ كود العقد.' : 'Contract source copied.')
      window.setTimeout(() => setCopied(false), 1800)
    } catch { setMessage(isAr ? 'تعذر النسخ؛ حدد الكود وانسخه يدوياً.' : 'Copy failed. Select and copy the source manually.') }
  }
  return <section className="token-studio">
    <div className="token-studio-intro panel">
      <div className="token-studio-heading"><span className="token-studio-icon"><ShieldCheck size={22}/></span><div><span className="official-tag">BASE · ERC-20</span><h2>{isAr ? 'استوديو إنشاء العملات' : 'Token Studio'}</h2><p>{isAr ? 'أنشئ مواصفات عملة ثابتة الإصدار وولّد عقد Solidity قابلاً للمراجعة.' : 'Configure a fixed-supply token and generate reviewable Solidity source.'}</p></div></div>
      <div className="token-studio-grid">
        <label>{isAr ? 'اسم العملة' : 'Token name'}<input value={name} maxLength={64} onChange={e=>setName(e.target.value)} placeholder="Example Token"/></label>
        <label>{isAr ? 'رمز العملة' : 'Token symbol'}<input value={symbol} maxLength={12} onChange={e=>setSymbol(e.target.value.toUpperCase().replace(/[^A-Z0-9]/g,''))} placeholder="EXM"/></label>
        <label className="token-supply-field">{isAr ? 'المعروض الأولي' : 'Initial supply'}<input inputMode="decimal" value={supply} onChange={e=>setSupply(e.target.value)} placeholder="1000000"/><small>18 decimals · {isAr ? 'كمية ثابتة لا يمكن زيادتها لاحقاً' : 'Fixed supply · cannot be increased later'}</small></label>
      </div>
      {!valid && <p className="token-validation" role="alert">{isAr ? 'تحقق من الاسم والرمز والكمية (حتى 18 منزلة عشرية).' : 'Check the name, symbol, and supply (up to 18 decimal places).'}</p>}
      <div className="token-wallet-row"><button type="button" className="button-ghost" onClick={()=>void connectWallet()} disabled={busy}><Wallet size={16}/>{busy ? 'Connecting…' : wallet ? wallet.slice(0,6)+'…'+wallet.slice(-4) : (isAr ? 'ربط المحفظة' : 'Connect wallet')}</button><span className={chainId.toLowerCase()===BASE_SEPOLIA?'token-network-ok':'token-network'}>{chainId.toLowerCase()===BASE_SEPOLIA ? 'Base Sepolia · Testnet' : chainId ? 'Switch to Base Sepolia' : 'Base Sepolia testnet'}</span></div>
      {message && <p className="token-status" role="status">{message}</p>}
    </div>
    <div className="panel token-preview">
      <div className="token-preview-head"><div><h3>{isAr ? 'معاينة العقد الذكي' : 'Smart contract preview'}</h3><p>{isAr ? 'عقد ERC-20 ثابت الإصدار مبني على OpenZeppelin.' : 'Fixed-supply ERC-20 using OpenZeppelin Contracts.'}</p></div><button type="button" className="button-primary" onClick={()=>void copySource()} disabled={!valid}>{copied ? <Check size={16}/> : <Copy size={16}/>} {copied ? 'Copied' : 'Copy Solidity'}</button></div>
      <pre className="token-source"><code>{source}</code></pre>
      <div className="token-actions"><a href="https://remix.ethereum.org/" target="_blank" rel="noopener noreferrer">Open Remix IDE <ExternalLink size={14}/></a><a href="https://docs.openzeppelin.com/contracts/5.x/erc20" target="_blank" rel="noopener noreferrer">OpenZeppelin ERC-20 docs <ExternalLink size={14}/></a></div>
    </div>
    <div className="token-safety panel"><ShieldCheck size={18}/><div><b>{isAr ? 'الإصدار التجريبي — لا يوجد نشر مباشر بعد' : 'Preview phase — direct deployment is not enabled yet'}</b><p>{isAr ? 'هذه المرحلة تولّد الكود فقط. لن نفعّل النشر داخل الموقع قبل نشر مصنع عقود مدقق على Base Sepolia واختباراته ومراجعة قانونية. لا تدخل عبارة الاسترداد أو المفتاح الخاص في الموقع.' : 'This phase generates source code only. In-app deployment stays disabled until a reviewed factory is deployed to Base Sepolia, automated tests pass, and legal review is complete. Never enter a recovery phrase or private key here.'}</p></div></div>
  </section>
}
